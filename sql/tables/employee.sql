
CREATE TABLE IF NOT EXISTS GIT_DEV_DB.APP.EMPLOYEE
(
    EMP_ID NUMBER,
    EMP_NAME VARCHAR(100),
    DEPARTMENT VARCHAR(100),
    SALARY NUMBER(10,2),
    CREATED_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

MERGE INTO GIT_DEV_DB.APP.EMPLOYEE AS TARGET
USING (
    SELECT
        COLUMN1::NUMBER AS EMP_ID,
        COLUMN2::VARCHAR(100) AS EMP_NAME,
        COLUMN3::VARCHAR(100) AS DEPARTMENT,
        COLUMN4::NUMBER(10,2) AS SALARY
    FROM VALUES
        (1, 'Rahul', 'IT', 50000),
        (2, 'Priya', 'Finance', 60000),
        (3, 'Amit', 'HR', 45000)
) AS SOURCE
ON TARGET.EMP_ID = SOURCE.EMP_ID

WHEN MATCHED THEN UPDATE SET
    TARGET.EMP_NAME = SOURCE.EMP_NAME,
    TARGET.DEPARTMENT = SOURCE.DEPARTMENT,
    TARGET.SALARY = SOURCE.SALARY

WHEN NOT MATCHED THEN INSERT
    (EMP_ID, EMP_NAME, DEPARTMENT, SALARY)
VALUES
    (SOURCE.EMP_ID, SOURCE.EMP_NAME, SOURCE.DEPARTMENT, SOURCE.SALARY);
